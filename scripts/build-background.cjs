const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const output = path.join(root, 'dist');
const read = file => fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n');
const { version } = JSON.parse(read('package.json'));
const atmosphere = read('src/atmosphere.js').split('\n');
const dust = atmosphere.find(line => line.startsWith('const dust='));
const web = atmosphere.slice(
  atmosphere.findIndex(line => line.includes('A receding, octagonal')),
  atmosphere.findIndex(line => line.includes('const vignette='))
).join('\n').replace('680/(z+450)', '680*projectionScale/(z+450)');
const worlds = ['worlds', 'worlds-extra', 'worlds-more', 'worlds-type'].map(name =>
  read('src/' + name + '.js').split('\n').filter(line => !line.startsWith('function drawAtmosphere('))
    .join('\n').replace('700/(z+450)', '700*projectionScale/(z+450)')
);
const sceneIds = ['web', ...worlds.flatMap(source =>
  [...source.matchAll(/([a-z]+):[a-zA-Z]+World\b/g)].map(match => match[1])
)];
const designs = [
  dust,
  'function webWorld(time, color) {',
  'const depth = 1, cx = W*.55-camera.x*.22, cy = H*.48-camera.y*.22;',
  web,
  '}',
  ...worlds,
  'backgroundWorlds.web = webWorld;'
].join('\n');
const license = read('LICENSE').trim().replace(/^/gm, ' * ');
const template = read('src/background-standalone.template.js');
const page = read('index.html').replace('src="./dist/fragments-background.js"', 'src="./fragments-background.js"');

fs.mkdirSync(output, { recursive: true });
fs.writeFileSync(path.join(output, 'fragments-background.js'),
  '/*! Fragments Backgrounds v' + version + ' | Generated by scripts/build-background.cjs\n' + license + '\n */\n' +
  template.replace('/* SCENE_IDS */ []', JSON.stringify(sceneIds))
    .replace('    // INSERT_DESIGNS', () => designs.replace(/^/gm, '    ')));
fs.writeFileSync(path.join(output, 'index.html'), page);
